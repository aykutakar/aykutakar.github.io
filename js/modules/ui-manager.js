        this.controls.backgroundUpload = document.getElementById('backgroundUpload');
        this.controls.presetBackground = document.getElementById('presetBackground');
        this.controls.animatedBackground = document.getElementById('animatedBackground');
        
        // Effects controls
        this.controls.addText = document.getElementById('addText');
        this.controls.addStickers = document.getElementById('addStickers');
        this.controls.particles = document.getElementById('particles');
        this.controls.lighting = document.getElementById('lighting');
        
        // Playback controls
        this.controls.playBtn = document.getElementById('playBtn');
        this.controls.pauseBtn = document.getElementById('pauseBtn');
        this.controls.stopBtn = document.getElementById('stopBtn');
        this.controls.timeDisplay = document.getElementById('timeDisplay');
        
        // Timeline controls
        this.controls.timelineSeeker = document.getElementById('timelineSeeker');
        this.controls.addKeyframe = document.getElementById('addKeyframe');
        this.controls.deleteKeyframe = document.getElementById('deleteKeyframe');
        
