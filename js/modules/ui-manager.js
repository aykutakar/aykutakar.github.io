    /**
     * Set up modal references
     */
    setupModals() {
        this.modals.avatarCustomization = {
            element: document.getElementById('avatarCustomizationModal'),
            body: document.getElementById('avatarCustomizationModal').querySelector('.modal-body')
        };
        
        this.modals.textEditor = {
            element: document.getElementById('textEditorModal'),
            body: document.getElementById('textEditorModal').querySelector('.modal-body')
        };
        
        this.modals.export = {
            element: document.getElementById('exportModal'),
            body: document.getElementById('exportModal').querySelector('.modal-body')
        };
        
        // Set up close buttons
        Object.values(this.modals).forEach(modal => {
            const closeBtn = modal.element.querySelector('.close-modal');
            if (closeBtn) {
                closeBtn.addEventListener('click', () => {
                    this.hideModal(modal.element);
                });
            }
            
            // Close on backdrop click
            modal.element.addEventListener('click', (e) => {
                if (e.target === modal.element) {
                    this.hideModal(modal.element);
                }
            });
        });
    }
    
    /**
     * Set up event listeners for all UI controls
     */
    setupEventListeners() {
        // Audio controls
        this.controls.loadAudio?.addEventListener('click', () => {
            this.controls.audioUpload.click();
        });
        
        this.controls.audioUpload?.addEventListener('change', (e) => {
            if (e.target.files[0]) {
                this.app.loadAudio(e.target.files[0]);
            }
        });
        
        this.controls.volumeControl?.addEventListener('input', (e) => {
            this.app.audio?.setVolume(e.target.value / 100);
        });
        
        // Avatar controls
        this.controls.customizeAvatar?.addEventListener('click', () => {
            this.showAvatarCustomizationModal();
        });
        
        // Dance controls
        this.controls.danceStyle?.addEventListener('change', (e) => {
            this.state.selectedDanceStyle = e.target.value;
        });
        
        this.controls.generateChoreography?.addEventListener('click', () => {
            this.app.generateDance();
        });
        
        this.controls.danceIntensity?.addEventListener('input', (e) => {
            this.state.danceIntensity = parseInt(e.target.value);
        });
        
        // Background controls
        this.controls.loadBackground?.addEventListener('click', () => {
            this.controls.backgroundUpload.click();
        });
        
        this.controls.backgroundUpload?.addEventListener('change', (e) => {
            if (e.target.files[0]) {
                this.loadBackground(e.target.files[0]);
            }
        });
        
        this.controls.presetBackground?.addEventListener('change', (e) => {
            this.loadPresetBackground(e.target.value);
        });
        
        // Effects controls
        this.controls.addText?.addEventListener('click', () => {
            this.showTextEditorModal();
        });
        
        // Playback controls
        this.controls.playBtn?.addEventListener('click', () => {
            this.app.play();
        });
        
        this.controls.pauseBtn?.addEventListener('click', () => {
            this.app.pause();
        });
        
        this.controls.stopBtn?.addEventListener('click', () => {
            this.app.stop();
        });
        
        // Timeline controls
        this.controls.timelineSeeker?.addEventListener('input', (e) => {
            const progress = e.target.value / 100;
            const time = progress * this.app.totalDuration;
            this.app.seek(time);
        });
        
        // Camera controls
        this.controls.cameraZoom?.addEventListener('input', (e) => {
            this.app.scene?.setCameraZoom(parseFloat(e.target.value));
        });
        
        this.controls.cameraRotation?.addEventListener('input', (e) => {
            this.app.scene?.setCameraRotation(parseFloat(e.target.value));
        });
        
        // Camera presets
        document.querySelectorAll('.preset-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                const preset = e.target.dataset.preset;
                this.setCameraPreset(preset);
            });
        });
        
        // Main navigation
        this.controls.newProject?.addEventListener('click', () => {
            this.app.newProject();
        });
        
        this.controls.loadProject?.addEventListener('click', () => {
            this.app.loadProject();
        });
        
        this.controls.saveProject?.addEventListener('click', () => {
            this.app.saveProject();
        });
        
        this.controls.exportVideo?.addEventListener('click', () => {
            this.showExportModal();
        });
    }
    
    /**
     * Update UI state
     */
    update(deltaTime) {
        if (!this.isInitialized) return;
        
        // Update time display
        this.updateTimeDisplay();
        
        // Update timeline seeker
        if (this.app.totalDuration > 0) {
            const progress = (this.app.currentTime / this.app.totalDuration) * 100;
            if (this.controls.timelineSeeker) {
                this.controls.timelineSeeker.value = progress;
            }
        }
    }
    
    /**
     * Update time display
     */
    updateTimeDisplay() {
        if (!this.controls.timeDisplay) return;
        
        const current = this.formatTime(this.app.currentTime);
        const total = this.formatTime(this.app.totalDuration);
        this.controls.timeDisplay.textContent = `${current} / ${total}`;
    }
    
    /**
     * Update playback controls state
     */
    updatePlaybackControls() {
        if (this.controls.playBtn) {
            this.controls.playBtn.style.opacity = this.app.isPlaying ? '0.5' : '1';
        }
        if (this.controls.pauseBtn) {
            this.controls.pauseBtn.style.opacity = this.app.isPlaying ? '1' : '0.5';
        }
    }
    
    /**
     * Update title with dirty state
     */
    updateTitle() {
        const title = 'Anime Dance Animation Generator';
        document.title = this.app.state.isDirty ? `${title} *` : title;
    }
    
    /**
     * Update performance monitor
     */
    updatePerformanceMonitor(fps, memory) {
        if (this.controls.fpsCounter) {
            this.controls.fpsCounter.textContent = Math.round(fps);
        }
        if (this.controls.memoryUsage) {
            this.controls.memoryUsage.textContent = `${Math.round(memory)} MB`;
        }
    }
    
    /**
     * Modal management
     */
    showModal(modal) {
        modal.classList.add('active');
        document.body.style.overflow = 'hidden';
    }
    
    hideModal(modal) {
        modal.classList.remove('active');
        document.body.style.overflow = '';
    }
    
