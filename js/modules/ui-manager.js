    /**
     * Set up avatar customization events
     */
    setupAvatarCustomizationEvents() {
        // Range inputs
        const ranges = ['faceShape', 'eyeSize', 'bodyHeight', 'bodyBuild'];
        ranges.forEach(id => {
            const input = document.getElementById(id);
            const display = input?.nextElementSibling;
            if (input && display) {
                input.addEventListener('input', (e) => {
                    display.textContent = e.target.value;
                    this.updateAvatarPreview();
                });
            }
        });
        
        // Color pickers
        document.querySelectorAll('.color-option').forEach(option => {
            option.addEventListener('click', (e) => {
                const group = e.target.parentElement;
                group.querySelectorAll('.color-option').forEach(opt => opt.classList.remove('active'));
                e.target.classList.add('active');
                this.updateAvatarPreview();
            });
        });
        
        // Presets
        document.querySelectorAll('.preset-avatar').forEach(preset => {
            preset.addEventListener('click', (e) => {
                document.querySelectorAll('.preset-avatar').forEach(p => p.classList.remove('active'));
                e.target.classList.add('active');
                this.loadAvatarPreset(e.target.dataset.preset);
            });
        });
    }
    
    /**
     * Set up text editor events
     */
    setupTextEditorEvents() {
        // Text input
        const textInput = document.getElementById('textInput');
        textInput?.addEventListener('input', () => {
            this.updateTextPreview();
        });
        
        // Font options
        document.querySelectorAll('.font-option').forEach(option => {
            option.addEventListener('click', (e) => {
                document.querySelectorAll('.font-option').forEach(opt => opt.classList.remove('active'));
                e.target.classList.add('active');
                this.updateTextPreview();
            });
        });
        
        // Animation paths
        document.querySelectorAll('.path-option').forEach(option => {
            option.addEventListener('click', (e) => {
                document.querySelectorAll('.path-option').forEach(opt => opt.classList.remove('active'));
                e.target.classList.add('active');
                this.updateTextPreview();
            });
        });
        
        // Font size
        const fontSize = document.getElementById('fontSize');
        const sizeDisplay = fontSize?.nextElementSibling;
        if (fontSize && sizeDisplay) {
            fontSize.addEventListener('input', (e) => {
                sizeDisplay.textContent = e.target.value;
                this.updateTextPreview();
            });
        }
    }
    
    /**
     * Set up export events
     */
    setupExportEvents() {
        // Format selection
        document.querySelectorAll('.format-option').forEach(option => {
            option.addEventListener('click', (e) => {
                document.querySelectorAll('.format-option').forEach(opt => opt.classList.remove('active'));
                e.target.classList.add('active');
            });
        });
        
        // Export button
        document.getElementById('startExport')?.addEventListener('click', () => {
            this.startExport();
        });
        
        // Cancel button
        document.getElementById('cancelExport')?.addEventListener('click', () => {
            this.hideModal(this.modals.export.element);
        });
    }
    
    /**
     * Helper methods
     */
    formatTime(seconds) {
        const mins = Math.floor(seconds / 60);
        const secs = Math.floor(seconds % 60);
        return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
    }
    
